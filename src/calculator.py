def add(a, b):
    """
    Add two numbers and return their sum.

    Parameters:
        a: The first number.
        b: The second number.

    Returns:
        The sum of a and b.
    """
    return a + b


def subtract(a, b):
    """
    Subtract the second number from the first.

    Parameters:
        a: The first number.
        b: The second number.

    Returns:
        The difference between a and b.
    """
    return a - b


print(add(10, 20))
print(subtract(20, 5))